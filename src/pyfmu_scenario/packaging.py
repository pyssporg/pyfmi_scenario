"""Build and package one scenario FMU.

The C++ sources are generated by :mod:`pyfmu_scenario.codegen`; this module
runs CMake, locates the built shared library, and delegates archive layout to
``pyssp_standard``'s :class:`FMU` facade. No zip is assembled here.
"""

from __future__ import annotations

import shutil
import subprocess
import tempfile
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

from pyssp_standard import FMU

from .codegen import (
    ScenarioSources,
    generate_scenario_sources,
)
from .grammar import Scenario, parse_scenario
from .model import (
    DEFAULT_GUID,
    MODEL_IDENTIFIER,
)
from .model_description import build_model_description

#: The only platform ``pyssp_standard`` packages on this workspace.
PLATFORM = "linux64"

#: Suffix of the shared library on the supported platform.
LIBRARY_SUFFIX = ".so"


@dataclass(frozen=True)
class ScenarioBuild:
    """A configured build directory and the library it produced."""

    directory: Path
    sources: ScenarioSources
    model_description: Path
    binary: Path


def load_scenario(scenario: Scenario | str | Path) -> Scenario:
    """Return a parsed scenario from typed input, text, or a file path."""
    if isinstance(scenario, Scenario):
        return scenario
    if isinstance(scenario, Path):
        return parse_scenario(scenario.read_text(encoding="utf-8"))
    if isinstance(scenario, str):
        return parse_scenario(scenario)
    raise TypeError(
        "scenario must be a Scenario, scenario text, or a path, got "
        f"{type(scenario).__name__}"
    )


def _require_tool(name: str) -> str:
    executable = shutil.which(name)
    if executable is None:
        raise RuntimeError(
            f"{name} was not found on PATH; install it to build the scenario "
            "FMU (CMake >= 3.16 and a C++17 compiler are required)"
        )
    return executable


def _run(command: Sequence[str], description: str, cwd: Path | None = None) -> None:
    completed = subprocess.run(
        list(command),
        cwd=None if cwd is None else str(cwd),
        capture_output=True,
        text=True,
        check=False,
    )
    if completed.returncode != 0:
        output = (completed.stdout + completed.stderr).strip()
        raise RuntimeError(
            f"{description} failed with exit code {completed.returncode}: "
            f"{' '.join(command)}\n{output}"
        )


def _library_path(build_directory: Path, stem: str) -> Path:
    expected = build_directory / f"{stem}{LIBRARY_SUFFIX}"
    if expected.is_file():
        return expected
    matches = sorted(build_directory.rglob(f"{stem}{LIBRARY_SUFFIX}"))
    if len(matches) == 1:
        return matches[0]
    raise FileNotFoundError(
        f"the build did not produce {expected}; cmake was run in "
        f"{build_directory}"
    )


def build_scenario(
    scenario: Scenario | str | Path,
    build_directory: str | Path,
    *,
    guid: str | None = None,
    cmake_extra: Sequence[str] | None = None,
) -> ScenarioBuild:
    """Generate sources, run CMake, and return the built library.

    ``build_directory`` is the source tree passed to ``cmake -S``; CMake's own
    output goes to ``<build_directory>/build``. ``cmake_extra`` is appended to
    the configure command (for example ``["-G", "Ninja"]``).
    """
    parsed = load_scenario(scenario)
    effective_guid = guid or DEFAULT_GUID
    directory = Path(build_directory)
    sources = generate_scenario_sources(
        parsed, directory, guid=effective_guid
    )

    description_path = directory / "modelDescription.xml"
    description_path.write_text(
        build_model_description(parsed, guid=effective_guid),
        encoding="utf-8",
    )

    cmake = _require_tool("cmake")
    configure = [
        cmake,
        "-S",
        str(directory),
        "-B",
        str(directory / "build"),
    ]
    if cmake_extra:
        configure.extend(cmake_extra)
    _run(configure, "cmake configure")
    _run(
        [cmake, "--build", str(directory / "build")],
        "cmake build",
    )

    binary = _library_path(directory / "build", sources.stem)
    return ScenarioBuild(
        directory=directory,
        sources=sources,
        model_description=description_path,
        binary=binary,
    )


def _package(build: ScenarioBuild, output: Path) -> Path:
    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    archive = FMU.package(
        output,
        model_description=build.model_description,
        binaries={PLATFORM: build.binary},
        fmi_version="2.0",
    )
    return Path(archive)


def package_scenario(
    scenario: Scenario | str | Path,
    output: str | Path,
    *,
    guid: str | None = None,
    model_id: str = MODEL_IDENTIFIER,
    keep_build_dir: str | Path | None = None,
    cmake_extra: Sequence[str] | None = None,
) -> Path:
    """Build ``scenario`` and write the FMI 2.0 ``.fmu`` archive ``output``.

    ``model_id`` may only be ``scenario``: the generated C symbols, the
    modelDescription identifiers, and the shared library name are fixed.
    ``keep_build_dir`` retains the generated sources and CMake build when an
    absolute directory is needed for inspection; otherwise a temporary tree is
    removed.
    """
    if model_id != MODEL_IDENTIFIER:
        raise ValueError(
            f"only model_id {MODEL_IDENTIFIER!r} is supported, got "
            f"{model_id!r}"
        )
    if keep_build_dir is not None:
        build = build_scenario(
            scenario,
            keep_build_dir,
            guid=guid,
            cmake_extra=cmake_extra,
        )
        return _package(build, Path(output))

    with tempfile.TemporaryDirectory(prefix="pyfmu_scenario_") as temporary:
        build = build_scenario(
            scenario,
            Path(temporary) / "scenario",
            guid=guid,
            cmake_extra=cmake_extra,
        )
        return _package(build, Path(output))


__all__ = [
    "LIBRARY_SUFFIX",
    "PLATFORM",
    "ScenarioBuild",
    "build_scenario",
    "load_scenario",
    "package_scenario",
]
